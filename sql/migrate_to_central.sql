-- ---------- 1) TABLES ----------

create table if not exists public.staff (
  id           bigint generated by default as identity primary key,
  branch       text,
  name         text,
  role         text default 'operator',
  can_approve  boolean default false,
  email        text,
  pin          text,
  active       boolean default true,
  created_at   timestamptz default now(),
  line_id      text
);
create unique index if not exists staff_line_id_uk on public.staff(line_id) where line_id is not null;

create table if not exists public.machine (
  id          bigint generated by default as identity primary key,
  branch      text not null,
  name        text not null,
  note        text not null default '',
  status      text not null default 'up',
  sort        integer not null default 0,
  updated_at  timestamptz not null default now(),
  unique (branch, name)
);

create table if not exists public.production_ticket (
  id            uuid primary key default gen_random_uuid(),
  branch        text,
  source        text default 'so',
  sonum         text default '',
  from_branch   text,
  so_cover      text default '',
  machine       text default '',
  material_key  text default '',
  label         text default '',
  item_seqs     integer[] default '{}'::integer[],
  oitems        jsonb,
  stage         smallint default 1,
  route         text,
  assignee      text default '',
  priority      integer default 0,
  coil_lot      text default '',
  waste_note    text default '',
  mat_m         numeric default 0,
  prod_m        numeric default 0,
  weight_kg     numeric default 0,
  sheets        integer default 0,
  max_len       numeric default 0,
  people        jsonb default '{}'::jsonb,
  created_by    bigint,
  created_at    timestamptz default now(),
  updated_at    timestamptz default now(),
  times         jsonb default '{}'::jsonb
);

create table if not exists public.online_job (
  id          uuid primary key default gen_random_uuid(),
  branch      text not null,
  platform    text not null default '',
  order_no    text not null,
  receiver    text not null default '',
  items       jsonb not null default '[]'::jsonb,
  status      text not null default 'new',
  created_by  bigint references public.staff(id),
  created_at  timestamptz not null default now()
);

create table if not exists public.ticket_event (
  id          bigint generated by default as identity primary key,
  ticket_id   uuid not null references public.production_ticket(id) on delete cascade,
  staff_id    bigint references public.staff(id),
  staff_name  text not null default '',
  action      text not null,
  from_stage  smallint,
  to_stage    smallint,
  detail      text not null default '',
  at          timestamptz not null default now()
);
create index if not exists ticket_event_ticket_idx on public.ticket_event(ticket_id);

create table if not exists public.shape_drawing (
  id          uuid primary key default gen_random_uuid(),
  branch      text not null,
  sonum       text not null,
  seq         integer not null,
  des         text default '',
  segs        jsonb not null default '[]'::jsonb,
  girth_mm    numeric default 0,
  updated_by  text default '',
  updated_at  timestamptz not null default now(),
  unique (branch, sonum, seq)
);

