-- ---------- 2) FUNCTIONS (พอร์ตตรงจาก live) ----------

create or replace function public.verify_pin(p_staff bigint, p_pin text)
returns boolean language sql security definer set search_path to 'public' as $$
  select exists (select 1 from public.staff where id = p_staff and pin = p_pin and active);
$$;

create or replace function public.staff_by_line_id(p_line_id text)
returns table(id bigint, branch text, name text, role text, can_approve boolean, email text, active boolean, line_id text)
language sql security definer set search_path to 'public' as $$
  select s.id, s.branch, s.name, s.role, s.can_approve, s.email, s.active, s.line_id
  from public.staff s where s.line_id = p_line_id and s.active = true;
$$;

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;

-- triggers updated_at (ตารางที่มี updated_at)
drop trigger if exists trg_touch_machine on public.machine;
create trigger trg_touch_machine before update on public.machine for each row execute function public.touch_updated_at();
drop trigger if exists trg_touch_ticket on public.production_ticket;
create trigger trg_touch_ticket before update on public.production_ticket for each row execute function public.touch_updated_at();
drop trigger if exists trg_touch_shape on public.shape_drawing;
create trigger trg_touch_shape before update on public.shape_drawing for each row execute function public.touch_updated_at();

-- ---------- 3) RLS + GRANTS (พอร์ตตรงจาก live: roles=public/anon+authenticated) ----------

-- ตารางปฏิบัติการ: anon+authenticated CRUD ได้เต็ม (จำเป็นสำหรับ PIN kiosk ที่ใช้ anon key)
do $$
declare t text;
begin
  foreach t in array array['machine','production_ticket','online_job','ticket_event','shape_drawing','so_live','so_item_live','coil_stock']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('grant select, insert, update, delete on public.%I to anon, authenticated', t);
    execute format('drop policy if exists %I on public.%I', t||'_all', t);
    execute format('create policy %I on public.%I for all to public using (true) with check (true)', t||'_all', t);
  end loop;
end $$;

-- staff: อ่านได้เฉพาะคอลัมน์ปลอดภัย (pin/line_id อ่านผ่าน RPC เท่านั้น) · ไม่มี policy write → เขียนไม่ได้จาก client
alter table public.staff enable row level security;
drop policy if exists staff_read on public.staff;
create policy staff_read on public.staff for select to public using (true);
revoke all on public.staff from anon, authenticated;
grant select (id, branch, name, role, can_approve, active, email) on public.staff to anon, authenticated;

-- RPC grants
revoke all on function public.verify_pin(bigint, text) from public;
grant execute on function public.verify_pin(bigint, text) to anon, authenticated;
revoke all on function public.staff_by_line_id(text) from public;
grant execute on function public.staff_by_line_id(text) to anon, authenticated;

-- ---------- 4) REALTIME (พอร์ตตรง: machine, so_live, online_job, production_ticket) ----------
do $$
declare t text;
begin
  foreach t in array array['machine','so_live','online_job','production_ticket']
  loop
    if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename=t) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;
